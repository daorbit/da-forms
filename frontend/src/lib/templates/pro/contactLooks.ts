export type ContactLook = keyof typeof LOOKS;

export function contactLook(id: ContactLook): FormTheme {
  return { ...LOOKS[id] };
}

export function inBothScopes(templates: FormTemplate[]): FormTemplate[] {
  return templates.flatMap((template) => [
    template,
    { ...template, id: `${template.id}-page`, theme: { ...template.theme, scope: 'page' } },
  ]);
}

export function large(fields: FormField[]): FormField[] {
  return fields.map((field) =>
    field.type === 'grid' && field.columns
      ? { ...field, columns: field.columns.map(large) }
      : { ...field, size: 'large' }
  );
}
