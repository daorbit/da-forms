export type TravelLook = keyof typeof LOOKS;

export function travelLook(id: TravelLook): FormTheme {
  return { ...LOOKS[id] };
}

export function travelScopes(templates: FormTemplate[]): FormTemplate[] {
  return templates.flatMap((template) => {
    const solid: FormTheme = { ...template.theme };
    delete solid.cardOpacity;
    delete solid.cardBlur;
    return [
      template,
      { ...template, id: `${template.id}-card`, theme: { ...solid, scope: 'card' } },
    ];
  });
}
